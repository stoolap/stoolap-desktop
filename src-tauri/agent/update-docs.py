#!/usr/bin/env python3
"""Copy the SQL-relevant pages of the Stoolap crate's docs into the app and
regenerate src/agent/docs_index.rs, which embeds them.

After a version change, also check agent/stoolap-sql-guide.md: `cargo test`
runs every SQL example in it on the new engine.

Run from src-tauri/ after changing the stoolap version in Cargo.toml:

    cargo fetch && python3 agent/update-docs.py

It reads the docs from the crate in Cargo's registry, so no network access
beyond `cargo fetch` is needed.
"""

import json
import pathlib
import re
import shutil
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
DEST = HERE / "stoolap-docs"
INDEX = HERE.parent / "src" / "agent" / "docs_index.rs"

# Pages about using SQL, the engine's behaviour and tuning. Drivers, install
# and contributor pages are left out: the agent never needs them.
SKIP_DIRS = {"drivers"}
SKIP_PAGES = {
    "development/building",
    "development/contributing",
    "development/testing",
    "development/migration-v037-to-v040",
    "getting-started/installation",
    "getting-started/api-reference",
    "getting-started/stoolap-studio",
    "getting-started/stoolap-desktop",
    "performance/ann-benchmarks",
}


def crate_dir() -> pathlib.Path:
    meta = json.loads(
        subprocess.check_output(
            ["cargo", "metadata", "--format-version", "1"], cwd=HERE.parent
        )
    )
    for pkg in meta["packages"]:
        if pkg["name"] == "stoolap":
            return pathlib.Path(pkg["manifest_path"]).parent
    sys.exit("stoolap is not a dependency of this crate")


def main() -> None:
    crate = crate_dir()
    src = crate / "docs" / "_docs"
    if DEST.exists():
        shutil.rmtree(DEST)
    pages = []
    for md in sorted(src.rglob("*.md")):
        page_id = md.relative_to(src).with_suffix("").as_posix()
        if page_id.split("/")[0] in SKIP_DIRS or page_id in SKIP_PAGES:
            continue
        out = DEST / f"{page_id}.md"
        out.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(md, out)
        text = md.read_text()
        m = re.search(r"^title:\s*(.+)$", text, re.M)
        title = m.group(1).strip().strip('"') if m else page_id
        pages.append((page_id, title))

    lines = [
        f"//! Generated by agent/update-docs.py from the {crate.name} crate's docs.",
        "//! Do not edit; rerun the script when the engine version changes.",
        "",
        "/// (page id, title, markdown with Jekyll front matter)",
        "pub const PAGES: &[(&str, &str, &str)] = &[",
    ]
    for page_id, title in pages:
        lines.append(
            f'    ({json.dumps(page_id)}, {json.dumps(title)}, include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/agent/stoolap-docs/{page_id}.md"))),'
        )
    lines.append("];")
    INDEX.write_text("\n".join(lines) + "\n")
    print(f"{len(pages)} pages from {crate.name}")


if __name__ == "__main__":
    main()
